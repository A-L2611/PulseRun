-- PulseRun Cloud storage; execute in Supabase Dashboard > SQL Editor.
create table if not exists public.runs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  run_id text not null,
  run_date text not null,
  minutes integer not null check (minutes between 1 and 240),
  rating integer not null check (rating between 1 and 10),
  feeling text not null check (feeling in ('good','normal','tired')),
  feeling_label text not null,
  title text not null default 'Lauftraining',
  created_at timestamptz not null default now(),
  unique (user_id, run_id)
);
alter table public.runs enable row level security;
drop policy if exists "Users can view their own runs" on public.runs;
create policy "Users can view their own runs" on public.runs for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users can insert their own runs" on public.runs;
create policy "Users can insert their own runs" on public.runs for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users can update their own runs" on public.runs;
create policy "Users can update their own runs" on public.runs for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Users can delete their own runs" on public.runs;
create policy "Users can delete their own runs" on public.runs for delete to authenticated using ((select auth.uid()) = user_id);
grant select, insert, update, delete on public.runs to authenticated;
